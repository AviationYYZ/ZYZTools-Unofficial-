'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {LocalTraining}=require('../electron-app/src/local-training');
const file=path.resolve(__dirname,'../scenarios/CYYZ-YYZ-YTP-Hold-Practice-FL110.json');
const practice=JSON.parse(fs.readFileSync(file,'utf8'));
const source=require('../scenarios/FL110/CYYZ-West-70-Default-1-FL110.json');
const background=source.aircraft.filter((_,index)=>index%2===0).map((a,i)=>({...a,altitude:11000,spawnTime:Math.round((i+.5)*3600/35)}));
const pilots=practice.aircraft.filter(a=>['ACA901','ACA902'].includes(a.callsign));
const points=new Map([...source.waypoints,...practice.waypoints].map(w=>[w.name,w]));
const output={...practice,name:'CYYZ YYZ/YTP Hold Practice | FL110 | 35 AAR Background',waypoints:[...points.values()],runways:source.runways,aircraft:[...pilots,...background]};
assert.equal(background.length,35);assert.equal(pilots.length,2);
assert.equal(new Set(output.aircraft.map(a=>a.squawk)).size,37);
const sim=new LocalTraining();sim.load(output);
assert(sim.aircraft.every(a=>a.altitude===11000));
sim.command('ACA901','HOLD DME YYZ N 180 R 000 10 15');
sim.command('ACA902','HOLD DME YTP S 000 L 180 10 15');
sim.tick(3600);
for(const cs of ['ACA901','ACA902'])assert(sim.aircraft.find(a=>a.callsign===cs)?.hold.laps>=2,cs);
fs.writeFileSync(file,JSON.stringify(output,null,2)+'\n');
console.log('Verified 35 background arrivals scheduled in one hour plus 2 hold aircraft at FL110.');
